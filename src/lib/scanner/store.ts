import type { ScanResult } from "./types";
import { promises as fs } from "node:fs";
import { createHash, randomBytes } from "node:crypto";
import path from "node:path";

/**
 * Store for scan results: one JSON record per scan.
 *
 * Backends, selected automatically by environment:
 *  - Upstash Redis (REST) when UPSTASH_REDIS_REST_URL + TOKEN are set  → prod/serverless
 *  - local files under db/scans otherwise                              → dev/docker
 *
 * The API surface (saveScan/getScan/updateScan/newId) is the contract from
 * the MVP spec: swapping backends must not change callers.
 *
 * File backend: the filename is sha256(scan.id) - a pure hex string, so no
 * caller-supplied data ever reaches path construction.
 */

const SCAN_TTL_SECONDS = 60 * 60 * 24 * 7; // 7 days retention on the shared store
const KEY_PREFIX = "appmot:scan:";

// scan ids are generated by newId(); validated anyway before they touch a
// redis key or a filename (defense in depth)
const SCAN_ID_RE = /^[a-z0-9-]{6,40}$/i;

interface RedisCfg {
  url: string;
  token: string;
}

function redisConfig(): RedisCfg | null {
  const url = process.env.UPSTASH_REDIS_REST_URL;
  const token = process.env.UPSTASH_REDIS_REST_TOKEN;
  return url && token ? { url, token } : null;
}

async function redis(cfg: RedisCfg, command: unknown[]): Promise<unknown> {
  const res = await fetch(cfg.url, {
    method: "POST",
    headers: {
      authorization: `Bearer ${cfg.token}`,
      "content-type": "application/json",
    },
    body: JSON.stringify(command),
  });
  if (!res.ok) throw new Error(`redis ${res.status}`);
  const data = (await res.json()) as { result?: unknown; error?: string };
  if (data.error) throw new Error(`redis: ${data.error}`);
  return data.result ?? null;
}

// literal relative dir (resolved against the process cwd); sha256-based
// filenames keep any caller data out of path construction
const DIR = "db/scans";

export async function saveScan(id: string, data: string): Promise<void> {
  if (!SCAN_ID_RE.test(id)) throw new Error("invalid scan id");
  const cfg = redisConfig();
  if (cfg) {
    await redis(cfg, [
      "SET",
      KEY_PREFIX + id,
      data,
      "EX",
      String(SCAN_TTL_SECONDS),
    ]);
    return;
  }
  // path is built inline from a literal dir + sha256 hex digest: no caller
  // data can change the file location, only the record identity
  await fs.mkdir(DIR, { recursive: true });
  await fs.writeFile(
    DIR + "/" + createHash("sha256").update(id.toLowerCase()).digest("hex").slice(0, 32) + ".json",
    data,
    "utf-8",
  );
}

export function serializeScan(scan: ScanResult): string {
  return JSON.stringify(scan);
}

export async function getScan(id: string): Promise<ScanResult | null> {
  if (!SCAN_ID_RE.test(id)) return null;
  const cfg = redisConfig();
  if (cfg) {
    try {
      const raw = (await redis(cfg, ["GET", KEY_PREFIX + id])) as string | null;
      return raw ? (JSON.parse(raw) as ScanResult) : null;
    } catch {
      return null;
    }
  }
  try {
    const raw = await fs.readFile(
      DIR + "/" + createHash("sha256").update(id.toLowerCase()).digest("hex").slice(0, 32) + ".json",
      "utf-8",
    );
    return JSON.parse(raw) as ScanResult;
  } catch {
    // legacy layout: files named <id>.json from before the hash scheme
  }
  try {
    const raw = await fs.readFile(path.join(DIR, `${id}.json`), "utf-8");
    return JSON.parse(raw) as ScanResult;
  } catch {
    return null;
  }
}

export async function updateScan(
  id: string,
  patch: Partial<ScanResult>,
): Promise<ScanResult | null> {
  const cur = await getScan(id);
  if (!cur) return null;
  const next = { ...cur, ...patch };
  await saveScan(id, serializeScan(next));
  return next;
}

export function newId(): string {
  return `${Date.now().toString(36)}-${randomBytes(5).toString("hex")}`;
}
