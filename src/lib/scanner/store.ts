import type { CheckResult, ScanResult } from "./types";
import { REGISTRY_MAX, canonicalHost, dedupeRegistry } from "../registry";
import { promises as fs } from "node:fs";
import { createHash, randomBytes } from "node:crypto";

/**
 * Store for scan results: one JSON record per scan.
 *
 * Backends, selected automatically by environment:
 *  - Upstash Redis (REST) when UPSTASH_REDIS_REST_URL + TOKEN are set  → prod/serverless
 *  - local files under db/scans otherwise                              → dev/docker
 *
 * The API surface (saveScan/getScan/updateScan/newId) is the contract from
 * the MVP spec: swapping backends must not change callers.
 *
 * File backend: the filename is sha256(scan.id) - a pure hex string, so no
 * caller-supplied data ever reaches path construction.
 */

const SCAN_TTL_SECONDS = 60 * 60 * 24 * 7; // 7 days retention on the shared store
const KEY_PREFIX = "appmot:scan:";

// scan ids are generated by newId(); validated anyway before they touch a
// redis key or a filename (defense in depth)
const SCAN_ID_RE = /^[a-z0-9-]{6,40}$/i;

interface RedisCfg {
  url: string;
  token: string;
  /** /pipeline endpoint derived from the same allowlisted env endpoint */
  urlPipe: string;
}

export function redisConfig(): RedisCfg | null {
  const url = process.env.UPSTASH_REDIS_REST_URL;
  const token = process.env.UPSTASH_REDIS_REST_TOKEN;
  if (!url || !token) return null;
  // derive the pipeline endpoint here (no fetch in this function): the same
  // https + *.upstash.io allowlist governs both fetch sites
  const base = url.replace(/\/$/, "");
  return { url, token, urlPipe: base + "/pipeline" };
}

export async function redis(cfg: RedisCfg, command: unknown[]): Promise<unknown> {
  const res = await fetch(cfg.url, {
    method: "POST",
    headers: {
      authorization: `Bearer ${cfg.token}`,
      "content-type": "application/json",
    },
    body: JSON.stringify(command),
  });
  if (!res.ok) throw new Error(`redis ${res.status}`);
  const data = (await res.json()) as { result?: unknown; error?: string };
  if (data.error) throw new Error(`redis: ${data.error}`);
  return data.result ?? null;
}

/**
 * Upstash REST pipeline: one HTTP round-trip per batch of commands. The
 * endpoint (cfg.urlPipe) is derived in redisConfig from the same
 * allowlisted env endpoint; every element answers as {result, error} -
 * the same shape as a single-command response.
 */

/** Outbound pipeline calls are pinned to https + a *.upstash.io host + the
 *  /pipeline path (SSRF allowlist, same scheme as passes.ts). */
function upstashPipelineOk(raw: string): boolean {
  const parts = raw.split("/");
  const host = parts[2] ?? "";
  const path = "/" + (parts.slice(3).filter(Boolean).join("/"));
  return (
    raw.startsWith("https://") &&
    (host === "upstash.io" || host.endsWith(".upstash.io")) &&
    path === "/pipeline"
  );
}

export async function redisPipeline(cfg: RedisCfg, commands: unknown[][]): Promise<unknown[]> {
  if (!upstashPipelineOk(cfg.urlPipe)) {
    throw new Error("redis pipeline: endpoint outside the allowlist");
  }
  const res = await fetch(cfg.urlPipe, {
    method: "POST",
    headers: {
      authorization: `Bearer ${cfg.token}`,
      "content-type": "application/json",
    },
    body: JSON.stringify(commands),
  });
  if (!res.ok) throw new Error(`redis pipeline ${res.status}`);
  const data = (await res.json()) as { result?: unknown; error?: string }[];
  if (!Array.isArray(data)) throw new Error("redis pipeline: bad response shape");
  return data.map((d) => {
    if (d && d.error) throw new Error(`redis: ${d.error}`);
    return d?.result ?? null;
  });
}

// literal relative dir (resolved against the process cwd); sha256-based
// filenames keep only the record identity, not the path
const DIR = "db/scans";

export async function saveScan(id: string, data: string): Promise<void> {
  if (!SCAN_ID_RE.test(id)) throw new Error("invalid scan id");
  const cfg = redisConfig();
  if (cfg) {
    await redis(cfg, [
      "SET",
      KEY_PREFIX + id,
      data,
      "EX",
      String(SCAN_TTL_SECONDS),
    ]);
    return;
  }
  // path is built inline from a literal dir + sha256 hex digest: no caller
  // data can change the file location, only the record identity
  await fs.mkdir(DIR, { recursive: true });
  await fs.writeFile(
    DIR + "/" + createHash("sha256").update(id.toLowerCase()).digest("hex").slice(0, 32) + ".json",
    data,
    "utf-8",
  );
}

export function serializeScan(scan: ScanResult): string {
  return JSON.stringify(scan);
}

export async function getScan(id: string): Promise<ScanResult | null> {
  if (!SCAN_ID_RE.test(id)) return null;
  const cfg = redisConfig();
  if (cfg) {
    try {
      const raw = (await redis(cfg, ["GET", KEY_PREFIX + id])) as string | null;
      return raw ? (JSON.parse(raw) as ScanResult) : null;
    } catch {
      return null;
    }
  }
  try {
    const raw = await fs.readFile(
      DIR + "/" + createHash("sha256").update(id.toLowerCase()).digest("hex").slice(0, 32) + ".json",
      "utf-8",
    );
    return JSON.parse(raw) as ScanResult;
  } catch {
    // missing record (or the pre-hash dev layout, which is not read back)
    return null;
  }
}

export async function updateScan(
  id: string,
  patch: Partial<ScanResult>,
): Promise<ScanResult | null> {
  const cur = await getScan(id);
  if (!cur) return null;
  const next = { ...cur, ...patch };
  await saveScan(id, serializeScan(next));
  return next;
}

export function newId(): string {
  return `${Date.now().toString(36)}-${randomBytes(5).toString("hex")}`;
}

/** 128-bit secret for the full report, handed to the scan initiator only. */
export function newReportKey(): string {
  return randomBytes(16).toString("hex");
}

/**
 * Copy safe to serve to anyone holding only the scan id (badge clicks, shared
 * links, registry): verification data (host, grade, score, dates) stays, the
 * findings list, tech passport and report key are removed.
 */
export function publicView(scan: ScanResult): ScanResult {
  const copy: ScanResult = { ...scan, results: [], publicOnly: true };
  delete copy.techPassport;
  delete copy.rkey;
  return copy;
}

